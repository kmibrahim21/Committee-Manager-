CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
DECLARE
  v_is_super BOOLEAN;
  v_name TEXT;
BEGIN
  v_is_super := CASE WHEN new.email IN ('thedevomix@gmail.com', 'kmibrahim@gmail.com') THEN true ELSE false END;
  v_name := COALESCE(new.raw_user_meta_data->>'name', new.raw_user_meta_data->>'madrasah_name', 'New Institution');

  -- Create Institution
  INSERT INTO public.institutions (id, name, email, is_super_admin)
  VALUES (new.id, v_name, new.email, v_is_super)
  ON CONFLICT (id) DO UPDATE SET 
    email = EXCLUDED.email,
    name = COALESCE(EXCLUDED.name, institutions.name);

  -- Create Profile
  INSERT INTO public.profiles (id, institution_id, full_name, role)
  VALUES (
    new.id, 
    new.id, 
    v_name, 
    CASE WHEN v_is_super THEN 'super_admin' ELSE 'org_admin' END
  )
  ON CONFLICT (id) DO UPDATE SET
    institution_id = EXCLUDED.institution_id,
    full_name = EXCLUDED.full_name;

  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

