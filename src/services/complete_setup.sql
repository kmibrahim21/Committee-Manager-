-- Approve Payment
CREATE OR REPLACE FUNCTION approve_payment_with_sms(t_id UUID, m_id UUID, sms_to_give INTEGER)
RETURNS JSON AS $$
DECLARE
    v_remaining_stock INTEGER;
BEGIN
    SELECT remaining_sms INTO v_remaining_stock FROM admin_sms_stock WHERE id = 1;
    
    IF v_remaining_stock < sms_to_give THEN
        RETURN json_build_object('success', false, 'error', 'ইনসাফিসিয়েন্ট সিস্টেম স্টক');
    END IF;

    -- Update Transaction
    UPDATE transactions SET status = 'approved', sms_count = sms_to_give WHERE id = t_id;
    
    -- Update Institution
    UPDATE institutions SET sms_balance = COALESCE(sms_balance, 0) + sms_to_give WHERE id = m_id;
    
    -- Update Stock
    UPDATE admin_sms_stock SET remaining_sms = remaining_sms - sms_to_give, last_updated = now() WHERE id = 1;
    
    RETURN json_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

